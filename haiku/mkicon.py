"""Writes Temino's Haiku vector icon (HVIF) and the resource file around it.

usage: python3 -I haiku/mkicon.py   (rewrites haiku/Temino.rdef)

The icon: a dark card holding two command blocks, each with a colored edge
like Temino's block list, and a prompt with a cursor. Shapes are polygons on
the 64x64 HVIF grid; rounded corners are sampled arcs.
"""
import math
import os

def rounded_rect(x0, y0, x1, y1, r, steps=6):
    points = []
    corners = [(x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)]
    for cx, cy, start in corners:
        for i in range(steps + 1):
            a = math.radians(start + 90 * i / steps)
            points.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return points

def rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

colors = {
    "shadow": (0, 0, 0, 0x55),
    "card": (0x15, 0x19, 0x22, 0xff),
    "rim": (0x2c, 0x34, 0x44, 0xff),
    "block": (0x23, 0x2a, 0x37, 0xff),
    "blue": (0x6c, 0xb6, 0xff, 0xff),
    "green": (0x7b, 0xd8, 0x8f, 0xff),
    "text": (0xd8, 0xde, 0xe9, 0xff),
    "dim": (0x56, 0x60, 0x73, 0xff),
}
shapes = [
    ("shadow", rounded_rect(5, 8, 61, 61, 10)),
    ("rim", rounded_rect(3, 5, 61, 59, 10)),
    ("card", rounded_rect(4.5, 6.5, 59.5, 57.5, 9)),
    ("block", rounded_rect(10, 13, 54, 24, 3)),
    ("blue", rect(10, 13, 13, 24)),
    ("dim", rect(17, 17.5, 40, 19.5)),
    ("block", rounded_rect(10, 28, 54, 39, 3)),
    ("green", rect(10, 28, 13, 39)),
    ("dim", rect(17, 32.5, 46, 34.5)),
    ("blue", [(10, 44), (13.5, 44), (19, 48.5), (13.5, 53), (10, 53), (15.5, 48.5)]),
    ("text", rect(23, 50.5, 33, 53)),
]

def coord(v):
    n = round((v + 128.0) * 102.0)
    return bytes([0x80 | (n >> 8), n & 0xff])

names = list(colors)
out = bytearray(b"ncif")
out.append(len(names))
for name in names:
    out += bytes([0x01, *colors[name]])          # solid color style
out.append(len(shapes))
for _, points in shapes:
    out += bytes([0x0a, len(points)])           # closed path, no curves
    for x, y in points:
        out += coord(x) + coord(y)
out.append(len(shapes))
for i, (style, _) in enumerate(shapes):
    out += bytes([0x0a, names.index(style), 1, i, 0x00])

here = os.path.dirname(os.path.abspath(__file__))
hexdata = out.hex()
lines = "\n".join(f'\t$"{hexdata[i:i + 64]}"' for i in range(0, len(hexdata), 64))
rdef = f'''// Generated by haiku/mkicon.py; edit that, not this.

resource app_signature "application/x-vnd.bluevisor-Temino";

resource app_flags B_MULTIPLE_LAUNCH;

resource app_version {{
	major  = 0,
	middle = 1,
	minor  = 0,
	variety = B_APPV_DEVELOPMENT,
	internal = 0,
	short_info = "Temino",
	long_info = "A modern GPU-accelerated terminal for Haiku"
}};

resource vector_icon array {{
{lines}
}};
'''
open(os.path.join(here, "Temino.rdef"), "w").write(rdef)
open(os.path.join(here, "temino.hvif"), "wb").write(out)
print(len(out), "bytes")
